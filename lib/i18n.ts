export type Word = keyof typeof words;
export const t = (lang: Lang, key: Word): string => words[key][lang === 'bn' ? 0 : 1];
export const text = (lang: Lang, bn: string, en: string) => (lang === 'bn' ? bn : en);
export function digits(v: string) {
  return v.replace(/[০-৯]/g, (c) => String('০১২৩৪৫৬৭৮৯'.indexOf(c))).replace(/,/g, '');
}
export const money = (v: number, lang: Lang = 'bn') =>
  new Intl.NumberFormat(lang === 'bn' ? 'bn-BD' : 'en-BD', {
    style: 'currency',
    currency: 'BDT',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(v);
export const number = (v: number, lang: Lang = 'bn') =>
  new Intl.NumberFormat(lang === 'bn' ? 'bn-BD' : 'en-BD', { maximumFractionDigits: 3 }).format(v);
export function date(v: string, lang: Lang = 'bn') {
  if (!v) return '—';
  const d = new Date(v.length === 10 ? v + 'T12:00:00+06:00' : v);
  return isNaN(d.getTime())
    ? '—'
    : new Intl.DateTimeFormat(lang === 'bn' ? 'bn-BD' : 'en-GB', {
        day: 'numeric',
        month: 'short',
        year: 'numeric',
        timeZone: 'Asia/Dhaka',
      }).format(d);
}
